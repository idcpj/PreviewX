import Foundation

let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
    .appendingPathComponent("Tests/Fixtures", isDirectory: true)

func write(_ relPath: String, _ content: String) throws {
    let url = root.appendingPathComponent(relPath)
    try content.write(to: url, atomically: true, encoding: .utf8)
    print("Wrote text: \(relPath)")
}

func writeData(_ relPath: String, _ data: Data) throws {
    let url = root.appendingPathComponent(relPath)
    try data.write(to: url)
    print("Wrote data: \(relPath) (\(data.count) bytes)")
}

