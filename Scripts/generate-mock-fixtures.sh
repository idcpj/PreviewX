#!/bin/zsh
set -euo pipefail

root=${0:A:h:h}
mock="$root/mock"
rm -rf "$mock"
mkdir -p "$mock"/{archives,code,database,structured,text}

print 'PreviewX plain-text fixture\nSecond line for search.' > "$mock/text/sample.txt"
cp "$mock/text/sample.txt" "$mock/text/sample.text"
print '2026-08-16T20:00:00Z INFO Preview started\n2026-08-16T20:00:01Z WARN Bounded preview enabled\n2026-08-16T20:00:02Z ERROR Example diagnostic' > "$mock/text/sample.log"
cp "$mock/text/sample.log" "$mock/text/sample.out"
cp "$mock/text/sample.log" "$mock/text/sample.trace"
print '# PreviewX Fixture\n\n## Heading\n\n- One\n- Two' > "$mock/text/sample.md"
cp "$mock/text/sample.md" "$mock/text/sample.markdown"
cp "$mock/text/sample.md" "$mock/text/sample.mdown"

print '{\n  "name": "PreviewX",\n  "enabled": true,\n  "items": ["one", "two"]\n}' > "$mock/structured/sample.json"
print '{\n  // Comment fixture\n  "name": "PreviewX"\n}' > "$mock/structured/sample.jsonc"
print '{"type":"Feature","properties":{"name":"PreviewX fixture"},"geometry":null}' > "$mock/structured/sample.geojson"
print '{"log":{"version":"1.2"},"entries":[]}' > "$mock/structured/sample.har"
print 'name: PreviewX\nenabled: true\nitems:\n  - one\n  - two' > "$mock/structured/sample.yaml"
cp "$mock/structured/sample.yaml" "$mock/structured/sample.yml"
print '[preview]\nname = "PreviewX"\nenabled = true' > "$mock/structured/sample.toml"
print '<preview enabled="true"><name>PreviewX</name><item>one</item></preview>' > "$mock/structured/sample.xml"
cp "$mock/structured/sample.xml" "$mock/structured/sample.xsd"
print '<svg xmlns="http://www.w3.org/2000/svg" width="120" height="50"><rect width="120" height="50" fill="steelblue"/><text x="10" y="30" fill="white">PreviewX</text></svg>' > "$mock/structured/sample.svg"
plutil -create xml1 "$mock/structured/sample.plist"
plutil -insert Name -string PreviewX "$mock/structured/sample.plist"
plutil -insert Enabled -bool YES "$mock/structured/sample.plist"
print 'name,score\nAda,98\nLin,91' > "$mock/structured/sample.csv"
print 'name\tscore\nAda\t98\nLin\t91' > "$mock/structured/sample.tsv"

print 'import Foundation\nprint("PreviewX")' > "$mock/code/sample.swift"
print '#include <stdio.h>\nint main(void) { puts("PreviewX"); }' > "$mock/code/sample.c"
cp "$mock/code/sample.c" "$mock/code/sample.h"
print '#import <Foundation/Foundation.h>\nint main(void) { return 0; }' > "$mock/code/sample.m"
cp "$mock/code/sample.m" "$mock/code/sample.mm"
print '#include <iostream>\nint main() { std::cout << "PreviewX"; }' > "$mock/code/sample.cpp"
cp "$mock/code/sample.cpp" "$mock/code/sample.cc"
cp "$mock/code/sample.cpp" "$mock/code/sample.cxx"
cp "$mock/code/sample.cpp" "$mock/code/sample.hpp"
print 'fn main() { println!("PreviewX"); }' > "$mock/code/sample.rs"
print 'package main\nimport "fmt"\nfunc main() { fmt.Println("PreviewX") }' > "$mock/code/sample.go"
print 'print("PreviewX")' > "$mock/code/sample.py"
cp "$mock/code/sample.py" "$mock/code/sample.pyw"
print 'console.log("PreviewX");' > "$mock/code/sample.js"
cp "$mock/code/sample.js" "$mock/code/sample.mjs"
cp "$mock/code/sample.js" "$mock/code/sample.cjs"
print 'export default function PreviewX() { return <main>PreviewX</main>; }' > "$mock/code/sample.jsx"
print 'export const title = "PreviewX";' > "$mock/code/sample.ts"
cp "$mock/code/sample.ts" "$mock/code/sample.tsx"
print 'class PreviewX { public static void main(String[] args) {} }' > "$mock/code/sample.java"
print 'fun main() = println("PreviewX")' > "$mock/code/sample.kt"
cp "$mock/code/sample.kt" "$mock/code/sample.kts"
print '#!/bin/sh\necho PreviewX' > "$mock/code/sample.sh"
cp "$mock/code/sample.sh" "$mock/code/sample.bash"
cp "$mock/code/sample.sh" "$mock/code/sample.zsh"
cp "$mock/code/sample.sh" "$mock/code/sample.fish"
print 'all:\n\techo PreviewX' > "$mock/code/Makefile"
print 'SELECT "PreviewX" AS name;' > "$mock/code/sample.sql"
print '<!doctype html><title>PreviewX</title><h1>PreviewX</h1>' > "$mock/code/sample.html"
cp "$mock/code/sample.html" "$mock/code/sample.htm"
print 'body { color: steelblue; }' > "$mock/code/sample.css"
cp "$mock/code/sample.css" "$mock/code/sample.scss"
cp "$mock/code/sample.css" "$mock/code/sample.sass"
cp "$mock/code/sample.css" "$mock/code/sample.less"
print 'FROM alpine:latest\nCMD ["echo", "PreviewX"]' > "$mock/code/Dockerfile"
print 'PREVIEWX_MODE=fixture' > "$mock/code/.env"
print '[preview]\nname=PreviewX' > "$mock/code/sample.ini"
cp "$mock/code/sample.ini" "$mock/code/sample.cfg"
cp "$mock/code/sample.ini" "$mock/code/sample.conf"

sqlite3 "$mock/database/sample.sqlite" 'CREATE TABLE preview (id INTEGER PRIMARY KEY, name TEXT); INSERT INTO preview(name) VALUES ("PreviewX");'
cp "$mock/database/sample.sqlite" "$mock/database/sample.sqlite3"
cp "$mock/database/sample.sqlite" "$mock/database/sample.db"

mkdir -p "$mock/.archive-source/PreviewX/Guides" "$mock/.archive-source/PreviewX/Sources"
print 'Archive preview fixture' > "$mock/.archive-source/PreviewX/README.txt"
print 'Nested content' > "$mock/.archive-source/PreviewX/Guides/nested.txt"
print 'print("archive")' > "$mock/.archive-source/PreviewX/Sources/main.swift"
(cd "$mock/.archive-source" && zip -qr "$mock/archives/sample.zip" PreviewX)
tar -C "$mock/.archive-source" -cf "$mock/archives/sample.tar" PreviewX
tar -C "$mock/.archive-source" -czf "$mock/archives/sample.tar.gz" PreviewX
cp "$mock/archives/sample.tar.gz" "$mock/archives/sample.tgz"
gzip -c "$mock/text/sample.txt" > "$mock/archives/sample.txt.gz"
cp "$mock/archives/sample.txt.gz" "$mock/archives/sample.txt.gzip"
printf '\x37\x7A\xBC\xAF\x27\x1C\x00\x04\x00\x00\x00\x00\x00\x00\x00\x00' > "$mock/archives/sample.7z"
rm -rf "$mock/.archive-source"

print 'Mock fixtures for every built-in PreviewX provider. Regenerate with scripts/generate-mock-fixtures.sh.' > "$mock/README.txt"
